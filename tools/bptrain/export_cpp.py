"""Write Source/Poly/BasicPitchWeights.h from the stock Basic Pitch ONNX (Apache-2.0, Spotify)."""
import sys, os, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bp_np
c = bp_np.consts(sys.argv[1] if len(sys.argv) > 1 else 'nmp_stock.onnx')
out = sys.argv[2] if len(sys.argv) > 2 else 'Source/Poly/BasicPitchWeights.h'
def arr(name, a):
    a = np.asarray(a, np.float32).ravel()
    body = ',\n'.join(', '.join(f'{v:.8e}f' for v in a[i:i + 8]) for i in range(0, len(a), 8))
    return f'inline constexpr float {name}[{len(a)}] = {{\n{body}\n}};\n'
s = ['// Generated by tools/bptrain/export_cpp.py from Spotify Basic Pitch (nmp.onnx, Apache License 2.0). Do not edit.\n',
     '#pragma once\nnamespace BasicPitchWeights {\n',
     arr('cqtRe', c['kA']), arr('cqtIm', c['kB']), arr('lowpass', c['lp']), arr('binScale', c['scale'])]
names = {(32, 8, 5, 5): 'onset1', (8, 8, 3, 39): 'cont1', (1, 8, 5, 5): 'cont2', (32, 1, 7, 7): 'note1', (1, 32, 7, 3): 'note2', (1, 33, 3, 3): 'onset2'}
for shp, nm in names.items():
    W, b, pads, strides = c['head'][shp]
    s.append(arr(nm + 'W', W)); s.append(arr(nm + 'B', b))
s.append('}\n'); open(out, 'w').write(''.join(s)); print(out, os.path.getsize(out), 'bytes')
